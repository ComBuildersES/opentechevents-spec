#!/usr/bin/env node
/**
 * Regenerates $defs.country's enum in spec/v0.4/event.schema.json from the officially assigned
 * ISO 3166-1 alpha-2 codes.
 *
 * The true authority — iso.org, the ISO Online Browsing Platform — returns 403 to automated
 * requests (tried with and without a realistic browser User-Agent), so this script cannot fetch
 * it directly. It fetches the Debian `iso-codes` project instead (used by glibc/GNOME across
 * most Linux distributions for this exact purpose), BUT does not trust it blindly: it compares
 * the fetch against scripts/data/iso-3166-1-alpha-2.json, a snapshot a human retrieved directly
 * from the OBP in a real browser (where the 403 does not apply) and recorded as "last confirmed
 * matching the official list on DATE". See docs/history/CHANGES.log #P005 and DECISIONS.md D006.
 *
 * If the two disagree, this refuses to update the schema and prints the difference instead:
 * a mismatch means the mirror has drifted from the real registry (or the registry changed) and
 * a human needs to re-visit the OBP by hand, confirm the new list, and update
 * scripts/data/iso-3166-1-alpha-2.json before this script is trusted again. This is the same
 * failure mode D005 almost shipped with (Intl silently disagreeing with the real ISO 4217 list)
 * — caught there only because it was checked by hand; here the check is permanent, not one-off.
 *
 * Maintenance script, not part of `npm run validate` or CI: ISO 3166-1 changes rarely.
 */
import { readFileSync, writeFileSync } from "node:fs";

const SCHEMA_PATH = new URL("../spec/v0.4/event.schema.json", import.meta.url);
const BASELINE_PATH = new URL("./data/iso-3166-1-alpha-2.json", import.meta.url);
const MIRROR_URL =
  "https://salsa.debian.org/iso-codes-team/iso-codes/-/raw/main/data/iso_3166-1.json";

const baseline = JSON.parse(readFileSync(BASELINE_PATH, "utf8"));
const baselineCodes = new Set(baseline.codes);

const res = await fetch(MIRROR_URL);
if (!res.ok) throw new Error(`fetch ${MIRROR_URL} failed: ${res.status}`);
const mirrorCodes = new Set((await res.json())["3166-1"].map((entry) => entry.alpha_2));

const onlyInBaseline = [...baselineCodes].filter((c) => !mirrorCodes.has(c)).sort();
const onlyInMirror = [...mirrorCodes].filter((c) => !baselineCodes.has(c)).sort();

if (onlyInBaseline.length || onlyInMirror.length) {
  console.error(
    `The Debian iso-codes mirror no longer matches the last human-verified OBP snapshot ` +
      `(retrieved ${baseline.retrievedAt} by ${baseline.retrievedBy}).`
  );
  if (onlyInBaseline.length) console.error(`  in the OBP snapshot but not the mirror: ${onlyInBaseline.join(", ")}`);
  if (onlyInMirror.length) console.error(`  in the mirror but not the OBP snapshot: ${onlyInMirror.join(", ")}`);
  console.error(
    `\nDo not trust either list yet. Visit https://www.iso.org/obp/ui/#search in a real ` +
      `browser, confirm which codes are actually officially assigned today, and update ` +
      `scripts/data/iso-3166-1-alpha-2.json (codes, retrievedBy, retrievedAt, note) before ` +
      `rerunning this script.`
  );
  process.exit(1);
}

const sorted = [...mirrorCodes].sort((a, b) => a.localeCompare(b));

const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
const country = schema.$defs.country;
country.enum = sorted;
country.$comment = `Generated by scripts/update-countries.mjs from the officially assigned ISO 3166-1 alpha-2 codes. Fetched from the Debian iso-codes project (${MIRROR_URL}) and verified to match a human-retrieved snapshot of the ISO Online Browsing Platform (retrieved ${baseline.retrievedAt} by ${baseline.retrievedBy}) before being trusted — iso.org itself returns 403 to automated requests. See docs/history/CHANGES.log #P005 / DECISIONS.md D006.`;
writeFileSync(SCHEMA_PATH, JSON.stringify(schema, null, 2) + "\n");

console.log(`${sorted.length} ISO 3166-1 alpha-2 codes (matches the OBP snapshot from ${baseline.retrievedAt})`);
console.log(`Updated ${SCHEMA_PATH.pathname}`);
