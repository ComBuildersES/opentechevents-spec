#!/usr/bin/env node
/**
 * Regenerates $defs.license's SPDX enum in spec/v0.3/event.schema.json from the official SPDX
 * License List, published as machine-readable JSON at github.com/spdx/license-list-data — the
 * SPDX project's own repository (a Linux Foundation project), not a third-party mirror.
 *
 * Fetches the latest tagged RELEASE, not the `main` branch: a git tag is an immutable snapshot,
 * so regenerating this later reproduces the same enum until a maintainer deliberately re-runs
 * this against a newer tag, the same reproducibility `update-timezones.mjs`/`update-currencies.mjs`
 * get from pinning to a dated release.
 *
 * Deprecated license IDs ARE included: SPDX itself states a deprecated identifier remains valid,
 * merely discouraged for new use — same reasoning as a renamed IANA timezone (D002) or a
 * withdrawn-but-still-meaningful currency is NOT (D005, `BGN` really is gone; the two are
 * different — SPDX explicitly keeps deprecated IDs valid, ISO 4217 does not keep withdrawn
 * currency codes valid, so each follows its own authority's actual rule).
 *
 * Only simple identifiers are covered, not SPDX license EXPRESSIONS (`AND`/`OR`/`WITH`,
 * `LicenseRef-...`) — see docs/history/CHANGES.log #P007 / DECISIONS.md D008 for why that is out of scope,
 * same reasoning as D007 scoping BCP 47 to its core.
 *
 * Also generates $defs.dataLicense — a NARROWER set used only by the recommended (quality, not
 * validity) profile: identifiers with no clause that can block a directory or aggregator from
 * redistributing or transforming the event (docs/history/CHANGES.log #P007's follow-up, DECISIONS.md D008).
 * NonCommercial (`-NC-`) rules out any commercial directory outright; NoDerivatives (`-ND-`)
 * blocks the reformatting/translation an aggregator routinely does; ShareAlike (`-SA-`, and
 * `ODbL-1.0`) is viral for a COMBINED database, so merging one event into a larger feed could
 * force the whole feed to adopt that license. A plain attribution or public-domain identifier
 * has none of these. Software copyleft licenses (GPL and family) are excluded from the
 * recommended set too — not because they are invalid (P007 already established real SPDX
 * identifiers are valid regardless of category), but because their copyleft mechanics are built
 * around "distributing the Program", legally murky applied to a JSON document, and that
 * ambiguity alone is enough to make a cautious directory's legal team decline rather than risk it.
 *
 * Maintenance script, not part of `npm run validate` or CI: run by hand when SPDX cuts a new
 * License List release.
 */
import { readFileSync, writeFileSync } from "node:fs";

const SCHEMA_PATH = new URL("../spec/v0.3/event.schema.json", import.meta.url);
const RELEASES_API = "https://api.github.com/repos/spdx/license-list-data/releases/latest";

const releaseRes = await fetch(RELEASES_API, {
  headers: { Accept: "application/vnd.github+json" },
});
if (!releaseRes.ok) throw new Error(`fetch ${RELEASES_API} failed: ${releaseRes.status}`);
const release = await releaseRes.json();
const tag = release.tag_name;

const dataUrl = `https://raw.githubusercontent.com/spdx/license-list-data/${tag}/json/licenses.json`;
const dataRes = await fetch(dataUrl);
if (!dataRes.ok) throw new Error(`fetch ${dataUrl} failed: ${dataRes.status}`);
const data = await dataRes.json();

const ids = [...new Set(data.licenses.map((l) => l.licenseId))].sort((a, b) => a.localeCompare(b));

// Plain public-domain-equivalent identifiers, plus any CC-BY-<version>[-<jurisdiction>] with no
// -NC-/-ND-/-SA- token between "BY" and the version number.
const PUBLIC_DOMAIN_EQUIVALENT = new Set(["CC0-1.0", "CC-PDDC", "CC-PDM-1.0", "PDDL-1.0", "ODC-By-1.0"]);
const PLAIN_CC_BY = /^CC-BY-\d/;
const dataLicenseIds = ids.filter((id) => PUBLIC_DOMAIN_EQUIVALENT.has(id) || PLAIN_CC_BY.test(id));

const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
const spdx = schema.$defs.license.anyOf[0];
spdx.enum = ids;
spdx.$comment = `Generated by scripts/update-licenses.mjs from the official SPDX License List (${tag}, ${data.licenseListVersion}, released ${data.releaseDate}) — github.com/spdx/license-list-data, the SPDX project's own repository. Includes deprecated IDs: SPDX states these remain valid, merely discouraged for new use. See docs/history/CHANGES.log #P007.`;

const dataLicense = schema.$defs.dataLicense;
dataLicense.enum = dataLicenseIds;
dataLicense.$comment = `Generated by scripts/update-licenses.mjs, same source and release as $defs.license. The subset with no clause (NonCommercial, NoDerivatives, ShareAlike) that can block a directory from redistributing or transforming an event, and no software-copyleft ambiguity. Used only by the recommended (quality) profile, never validity. See docs/history/CHANGES.log #P007 / DECISIONS.md D008.`;

writeFileSync(SCHEMA_PATH, JSON.stringify(schema, null, 2) + "\n");

console.log(`SPDX License List ${tag} (${data.licenseListVersion}): ${ids.length} identifiers, ${dataLicenseIds.length} recommended`);
console.log(`Updated ${SCHEMA_PATH.pathname}`);
