#!/usr/bin/env node
/**
 * Regenerates $defs.currency's enum in spec/v0.3/event.schema.json from the official ISO 4217
 * active-currency list, published by SIX Group (the ISO-designated maintenance agency) —
 * NOT from `Intl.supportedValuesOf('currency')`. That API bundles whatever CLDR/ICU snapshot
 * shipped with the running Node, which lags the real registry: it still accepts BGN (Bulgarian
 * Lev), withdrawn 2026-01 when Bulgaria adopted the euro, along with several other retired
 * codes (ANG, CUC, HRK, SLL, ZWL) — see CHANGES.log #P004 for how that was caught and verified
 * against the official list rather than assumed.
 *
 * Maintenance script, not part of `npm run validate` or CI: run by hand when SIX Group
 * publishes an amendment (see https://www.six-group.com/en/products-services/financial-information/market-reference-data/data-standards/iso-currency.html).
 */
import { readFileSync, writeFileSync } from "node:fs";

const SCHEMA_PATH = new URL("../spec/v0.3/event.schema.json", import.meta.url);
const LIST_URL =
  "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml";

const res = await fetch(LIST_URL);
if (!res.ok) throw new Error(`fetch ${LIST_URL} failed: ${res.status}`);
const xml = await res.text();

const published = /<ISO_4217 Pblshd="([^"]+)"/.exec(xml)?.[1];
if (!published) throw new Error("could not find the Pblshd date in list-one.xml");

const codes = new Set([...xml.matchAll(/<Ccy>([A-Z]{3})<\/Ccy>/g)].map((m) => m[1]));
const sorted = [...codes].sort((a, b) => a.localeCompare(b));

const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
const currency = schema.$defs.currency;
currency.enum = sorted;
currency.$comment = `Generated by scripts/update-currencies.mjs from the official ISO 4217 active-currency list published by SIX Group (list-one.xml, published ${published}) — not from Intl.supportedValuesOf('currency'), which lags the real registry. See CHANGES.log #P004.`;
writeFileSync(SCHEMA_PATH, JSON.stringify(schema, null, 2) + "\n");

console.log(`${sorted.length} ISO 4217 currency codes (published ${published})`);
console.log(`Updated ${SCHEMA_PATH.pathname}`);
